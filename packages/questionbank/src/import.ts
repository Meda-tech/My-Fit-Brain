import { attachRules, type LatestVersionRules } from './attach-rules';
import { parseWorkbook, type KnownTest } from './parse-excel';
import type { ImportPayload, RulesSource, ValidationIssue } from './types';
import { hasErrors, validatePayload } from './validate';

// One code path for every import (admin screen and CLI): parse → attach rules → validate.

export interface ImportPreview {
  test_code: string;
  version_label: string;
  source_file_name: string;
  tab_counts: Record<string, number>;
  counts: Record<string, number>;
}

export interface PreparedImport {
  payload: ImportPayload | null;
  preview: ImportPreview | null;
  source: RulesSource | null;
  /** Parse and rule-attachment problems; any error blocks creating a draft. */
  errors: string[];
  warnings: string[];
  issues: ValidationIssue[];
  ok: boolean;
}

export async function prepareImport(
  data: ArrayBuffer | Uint8Array,
  options: {
    fileName: string;
    tests: KnownTest[];
    loadLatest?: (testCode: string) => Promise<LatestVersionRules | null>;
    changeNote?: string | null;
  }
): Promise<PreparedImport> {
  const parsed = await parseWorkbook(data, { fileName: options.fileName, tests: options.tests });
  if (!parsed.payload) {
    return { payload: null, preview: null, source: null, errors: parsed.errors, warnings: parsed.warnings, issues: [], ok: false };
  }
  const content = parsed.payload;
  const preview: ImportPreview = {
    test_code: content.test_code,
    version_label: content.version_label,
    source_file_name: content.source_file_name,
    tab_counts: content.tab_counts,
    counts: {
      modules: content.modules.length,
      questions: content.questions.length,
      options: content.options.length,
      texts: content.texts.length,
      item_texts: content.item_texts.length,
      tiers: content.tiers.length,
    },
  };

  const attached = await attachRules(content, { loadLatest: options.loadLatest, changeNote: options.changeNote });
  const warnings = [...parsed.warnings, ...attached.warnings];
  if (!attached.payload) {
    return { payload: null, preview, source: attached.source, errors: attached.errors, warnings, issues: [], ok: false };
  }
  const payload = attached.payload;
  Object.assign(preview.counts, {
    point_rules: payload.point_rules.length,
    overrides: payload.overrides.length,
    visibility_rules: payload.visibility_rules.length,
    option_rules: payload.option_rules.length,
    flags: payload.flags.length,
    format_rules: payload.format_rules.length,
    test_cases: payload.test_cases.length,
  });

  const issues = validatePayload(payload);
  return { payload, preview, source: attached.source, errors: [], warnings, issues, ok: !hasErrors(issues) };
}

/** SQL that imports a payload as a new draft (for running in the Supabase SQL Editor). */
export function toImportSql(payload: ImportPayload): string {
  const json = JSON.stringify(payload);
  let tag = 'qbjson';
  while (json.includes(`$${tag}$`)) tag += '_';
  return [
    `-- Import ${payload.test_code} ${payload.version_label} (${payload.source_file_name}) as a new draft.`,
    `-- Generated by \`npm run qb:import -- <file> --sql <out.sql>\`. Run once in the Supabase SQL Editor.`,
    `select public.qb_import_version($${tag}$${json}$${tag}$::jsonb) as version_id;`,
    '',
  ].join('\n');
}
